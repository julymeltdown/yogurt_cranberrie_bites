// Test/development-only generator. Canonical schemas remain the wire authority.
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
const root = new URL('../../../../../', import.meta.url)
const paths = ['contracts/realtime/v1/world.schema.json', 'contracts/core/v1/core.schema.json', 'contracts/assets/v1/avatar-config.schema.json', 'contracts/assets/v1/common.schema.json']
const docs = paths.map(p => JSON.parse(readFileSync(new URL(p, root))))
const names = new Map(), definitions = []
function refName(ref, doc) {
  const [id, pointer] = ref.split('#')
  const target = id ? docs.find(d => d.$id === id) : doc
  if (!target || !pointer?.startsWith('/$defs/')) throw Error('Unknown reference')
  const key = pointer.slice(7), identity = `${target.$id}#${pointer}`
  if (!names.has(identity)) {
    const name = key === 'AvatarConfig' ? 'AvatarConfig' : key
    if ([...names.values()].includes(name)) throw Error('Name collision')
    names.set(identity, name)
    definitions.push([name, target.$defs[key], target])
  }
  return names.get(identity)
}
function type(s, doc) {
  if (s.$ref) return refName(s.$ref, doc)
  if ('const' in s) return JSON.stringify(s.const)
  if (s.enum) return s.enum.map(v => JSON.stringify(v)).join(' | ')
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(v => `(${type(v, doc)})`).join(' | ')
  if (s.type === 'object') return `{ ${Object.entries(s.properties ?? {}).map(([k,v]) => `readonly ${JSON.stringify(k)}${s.required?.includes(k) ? '' : '?'}: ${type(v, doc)}`).join('; ')} }`
  if (s.type === 'array') return `readonly (${type(s.items, doc)})[]`
  return ({ integer: 'number', number: 'number', string: 'string', boolean: 'boolean', null: 'null' })[s.type] ?? (() => { throw Error('Unsupported type') })()
}
for (const key of Object.keys(docs[0].$defs)) refName(`#/$defs/${key}`, docs[0])
const output = ['// Generated by __tests__/generate-types.mjs; do not edit independently.', ...paths.map(p => `// source_hash ${p} ${createHash('sha256').update(readFileSync(new URL(p, root))).digest('hex')}`)]
for (const [name, schema, doc] of definitions) output.push(`export type ${name} = ${type(schema, doc)}`)
const destination = new URL('../transport/wire-types.ts', import.meta.url), content = `${output.join('\n')}\n`
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== content) throw Error('Generated C05 types drifted')
} else writeFileSync(destination, content)
