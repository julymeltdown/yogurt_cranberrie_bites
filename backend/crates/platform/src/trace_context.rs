//! Bounded W3C Trace Context propagation across HTTP and internal gRPC.
//!
//! Trace context is caller-controlled correlation data, never an authorization
//! input. `tracestate` is kept opaque, bounded, and out of logs. The sampled bit
//! is propagated unchanged without an OTLP SDK. With OTLP enabled, the SDK's
//! sampler makes and propagates the local recording decision.

use http::{HeaderMap, HeaderValue};
use opentelemetry::{
    context::Context as OtelContext,
    trace::{SpanContext as OtelSpanContext, SpanId, TraceContextExt, TraceFlags, TraceId},
};
use std::collections::HashSet;
use tonic::metadata::{Ascii, MetadataValue};
use tonic::{Request, Status};
use tracing::{field, Instrument, Span};
use tracing_opentelemetry::OpenTelemetrySpanExt;

pub const TRACEPARENT_HEADER: &str = "traceparent";
pub const TRACESTATE_HEADER: &str = "tracestate";
pub const MAX_TRACEPARENT_LENGTH: usize = 512;
pub const MAX_TRACESTATE_LENGTH: usize = 512;
const SAMPLED_FLAG: u8 = 0x01;

tokio::task_local! {
    static CURRENT: TraceContext;
}

/// Trace identifiers for one server-side request span.
#[derive(Clone, PartialEq, Eq)]
pub struct TraceContext {
    trace_id: String,
    span_id: String,
    parent_span_id: Option<String>,
    trace_flags: u8,
    tracestate: Option<String>,
}

impl std::fmt::Debug for TraceContext {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("TraceContext")
            .field("trace_id", &self.trace_id)
            .field("span_id", &self.span_id)
            .field("parent_span_id", &self.parent_span_id)
            .field("sampled", &self.sampled())
            .field("tracestate_present", &self.tracestate.is_some())
            .finish()
    }
}

#[derive(Clone, PartialEq, Eq)]
struct ParentContext {
    trace_id: String,
    span_id: String,
    trace_flags: u8,
}

impl TraceContext {
    /// Start a server span from validated inbound headers, or start a fresh trace.
    /// An invalid parent never controls the generated identifiers or carries
    /// `tracestate` into the service.
    pub fn from_headers(headers: &HeaderMap) -> Self {
        let parent = single_header(headers, TRACEPARENT_HEADER)
            .and_then(|value| parse_traceparent(value.as_bytes()));
        let tracestate = parent
            .as_ref()
            .and_then(|_| parse_tracestate(headers.get_all(TRACESTATE_HEADER)));

        let (trace_id, parent_span_id, trace_flags) = match parent {
            Some(parent) => (parent.trace_id, Some(parent.span_id), parent.trace_flags),
            None => (new_trace_id(), None, 0),
        };

        Self {
            trace_id,
            span_id: new_span_id(),
            parent_span_id,
            trace_flags,
            tracestate,
        }
    }

    /// Start an asynchronous child span from a validated, persisted W3C parent.
    /// No vendor state is retained across the queue boundary. Invalid or absent
    /// parents return `None` rather than creating an unrelated trace.
    pub fn child_from_traceparent(value: &str) -> Option<Self> {
        let parent = parse_traceparent(value.as_bytes())?;
        Some(Self {
            trace_id: parent.trace_id,
            span_id: new_span_id(),
            parent_span_id: Some(parent.span_id),
            trace_flags: parent.trace_flags,
            tracestate: None,
        })
    }

    /// Start a client span below this validated context while retaining its
    /// opaque, already-validated `tracestate` for the synchronous RPC hop.
    pub fn child(&self) -> Self {
        Self {
            trace_id: self.trace_id.clone(),
            span_id: new_span_id(),
            parent_span_id: Some(self.span_id.clone()),
            trace_flags: self.trace_flags,
            tracestate: self.tracestate.clone(),
        }
    }

    pub fn trace_id(&self) -> &str {
        &self.trace_id
    }

    pub fn span_id(&self) -> &str {
        &self.span_id
    }

    pub fn parent_span_id(&self) -> Option<&str> {
        self.parent_span_id.as_deref()
    }

    pub fn sampled(&self) -> bool {
        self.trace_flags & SAMPLED_FLAG != 0
    }

    pub fn tracestate(&self) -> Option<&str> {
        self.tracestate.as_deref()
    }

    /// The current W3C version-00 representation for an outgoing child call.
    pub fn traceparent(&self) -> String {
        format!(
            "00-{}-{}-{:02x}",
            self.trace_id,
            self.span_id,
            self.trace_flags & SAMPLED_FLAG
        )
    }

    /// Bind the tracing span to this validated remote parent, then use the
    /// OpenTelemetry SDK's actual child identifiers and sampling decision when
    /// an OTLP layer is installed. Without that layer, retain the secure local
    /// fallback identifiers generated by this type.
    pub fn bind_to_span(&mut self, span: &Span) {
        if let Some(parent) = self.otel_parent_context() {
            // This can fail when no OpenTelemetry layer is installed. In that
            // case `span.context()` below is invalid and the fallback remains.
            let _ = span.set_parent(parent);
        }

        let span_context = span.context().span().span_context().clone();
        if span_context.is_valid() {
            self.trace_id = format!("{:032x}", span_context.trace_id());
            self.span_id = format!("{:016x}", span_context.span_id());
            self.trace_flags = span_context.trace_flags().to_u8() & SAMPLED_FLAG;
        }
    }

    /// Record the IDs represented by this context into a span whose fields are
    /// deliberately declared empty until after OpenTelemetry parent binding.
    pub fn record_on_span(&self, span: &Span) {
        span.record("trace_id", self.trace_id.as_str());
        span.record("span_id", self.span_id.as_str());
        span.record(
            "parent_span_id",
            self.parent_span_id.as_deref().unwrap_or_default(),
        );
        span.record("sampled", self.sampled());
    }

    fn otel_parent_context(&self) -> Option<OtelContext> {
        let parent_span_id = self.parent_span_id.as_deref()?;
        let trace_id = TraceId::from_hex(&self.trace_id).ok()?;
        let span_id = SpanId::from_hex(parent_span_id).ok()?;
        let parent = OtelSpanContext::new(
            trace_id,
            span_id,
            TraceFlags::new(self.trace_flags),
            true,
            // `tracestate` remains bounded and may pass over the synchronous
            // internal gRPC hop, but opaque vendor values are not exported.
            Default::default(),
        );
        parent
            .is_valid()
            .then(|| OtelContext::new().with_remote_span_context(parent))
    }
}

/// Current server span context, if a transport layer established one.
pub fn current() -> Option<TraceContext> {
    CURRENT.try_with(Clone::clone).ok()
}

/// Bind the current validated W3C context as the parent of a local child span.
///
/// The returned context contains the child span identifiers (including the
/// SDK's sampling decision when an OpenTelemetry layer is installed). This
/// does not change the task-local context, so asynchronous work that persists
/// the request's original parent continues to do so.
pub fn bind_current_child_to_span(span: &Span) -> Option<TraceContext> {
    let mut context = current()?.child();
    context.bind_to_span(span);
    context.record_on_span(span);
    Some(context)
}

/// Run asynchronous work inside a validated request or background child scope.
pub async fn scope<F>(context: TraceContext, future: F) -> F::Output
where
    F: std::future::Future,
{
    CURRENT.scope(context, future).await
}

/// Attach the current trace context to an internal gRPC request.
///
/// Existing values are cleared first so caller-supplied metadata cannot bypass
/// ingress validation. Calls outside a request scope carry no trace context.
#[allow(clippy::result_large_err)]
pub fn attach<T>(request: &mut Request<T>) -> Result<(), Status> {
    let metadata = request.metadata_mut();
    metadata.remove(TRACEPARENT_HEADER);
    metadata.remove(TRACESTATE_HEADER);

    let Some(context) = current() else {
        return Ok(());
    };

    let traceparent: MetadataValue<Ascii> = context
        .traceparent()
        .parse()
        .map_err(|_| Status::internal("traceparent is not valid gRPC metadata"))?;
    metadata.insert(TRACEPARENT_HEADER, traceparent);

    if let Some(tracestate) = context.tracestate() {
        let tracestate: MetadataValue<Ascii> = tracestate
            .parse()
            .map_err(|_| Status::internal("tracestate is not valid gRPC metadata"))?;
        metadata.insert(TRACESTATE_HEADER, tracestate);
    }
    Ok(())
}

/// A Tower layer that validates inbound W3C context, creates a request span, and
/// makes that span's context available to downstream gRPC interceptors.
#[derive(Clone, Copy, Debug, Default)]
pub struct TraceContextLayer;

impl<S> tower::Layer<S> for TraceContextLayer {
    type Service = TraceContextService<S>;

    fn layer(&self, inner: S) -> Self::Service {
        TraceContextService { inner }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct TraceContextService<S> {
    inner: S,
}

impl<S, Body> tower::Service<http::Request<Body>> for TraceContextService<S>
where
    S: tower::Service<http::Request<Body>>,
    S::Future: Send + 'static,
{
    type Response = S::Response;
    type Error = S::Error;
    type Future =
        std::pin::Pin<Box<dyn std::future::Future<Output = Result<S::Response, S::Error>> + Send>>;

    fn poll_ready(
        &mut self,
        context: &mut std::task::Context<'_>,
    ) -> std::task::Poll<Result<(), Self::Error>> {
        self.inner.poll_ready(context)
    }

    fn call(&mut self, request: http::Request<Body>) -> Self::Future {
        let mut context = TraceContext::from_headers(request.headers());
        let span = tracing::info_span!(
            parent: None,
            "request",
            trace_id = field::Empty,
            span_id = field::Empty,
            parent_span_id = field::Empty,
            sampled = field::Empty,
        );
        context.bind_to_span(&span);
        context.record_on_span(&span);
        let future = self.inner.call(request);
        Box::pin(async move {
            async move {
                scope(context, async move {
                    let result = future.await;
                    tracing::debug!(succeeded = result.is_ok(), "request completed");
                    result
                })
                .await
            }
            .instrument(span)
            .await
        })
    }
}

fn single_header<'a>(headers: &'a HeaderMap, name: &str) -> Option<&'a HeaderValue> {
    let mut values = headers.get_all(name).iter();
    let value = values.next()?;
    values.next().is_none().then_some(value)
}

fn parse_traceparent(value: &[u8]) -> Option<ParentContext> {
    if value.len() < 55 || value.len() > MAX_TRACEPARENT_LENGTH {
        return None;
    }
    if value.get(2) != Some(&b'-') || value.get(35) != Some(&b'-') || value.get(52) != Some(&b'-') {
        return None;
    }

    let version = parse_hex_byte(&value[0..2])?;
    if version == 0xff {
        return None;
    }
    if version == 0 {
        if value.len() != 55 {
            return None;
        }
    } else if value.len() > 55 && value[55] != b'-' {
        // Future versions may append fields, but must keep the version-00
        // prefix parseable. Unknown suffixes are discarded when downgraded.
        return None;
    }

    let trace_id = &value[3..35];
    let span_id = &value[36..52];
    if !trace_id.iter().copied().all(is_lower_hex)
        || !span_id.iter().copied().all(is_lower_hex)
        || trace_id.iter().all(|byte| *byte == b'0')
        || span_id.iter().all(|byte| *byte == b'0')
    {
        return None;
    }

    let trace_flags = parse_hex_byte(&value[53..55])? & SAMPLED_FLAG;
    Some(ParentContext {
        trace_id: std::str::from_utf8(trace_id).ok()?.to_owned(),
        span_id: std::str::from_utf8(span_id).ok()?.to_owned(),
        trace_flags,
    })
}

fn parse_hex_byte(value: &[u8]) -> Option<u8> {
    if value.len() != 2 || !value.iter().copied().all(is_lower_hex) {
        return None;
    }
    let high = hex_nibble(value[0])?;
    let low = hex_nibble(value[1])?;
    Some((high << 4) | low)
}

fn is_lower_hex(value: u8) -> bool {
    value.is_ascii_digit() || (b'a'..=b'f').contains(&value)
}

fn hex_nibble(value: u8) -> Option<u8> {
    match value {
        b'0'..=b'9' => Some(value - b'0'),
        b'a'..=b'f' => Some(value - b'a' + 10),
        _ => None,
    }
}

fn parse_tracestate(values: http::header::GetAll<'_, HeaderValue>) -> Option<String> {
    let mut combined = String::new();
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            combined.push(',');
        }
        combined.push_str(value.to_str().ok()?);
        if combined.len() > MAX_TRACESTATE_LENGTH {
            return None;
        }
    }
    normalize_tracestate(&combined)
}

fn normalize_tracestate(value: &str) -> Option<String> {
    if value.len() > MAX_TRACESTATE_LENGTH {
        return None;
    }
    let entries = value.split(',').collect::<Vec<_>>();
    if entries.len() > 32 {
        return None;
    }

    let mut keys = HashSet::new();
    let mut normalized = Vec::with_capacity(entries.len());
    for entry in entries {
        let entry = entry.trim_matches(|character| character == ' ' || character == '\t');
        if entry.is_empty() {
            continue;
        }
        let (key, value) = entry.split_once('=')?;
        if !valid_tracestate_key(key) || !valid_tracestate_value(value) || !keys.insert(key) {
            return None;
        }
        normalized.push(entry);
    }

    (!normalized.is_empty()).then(|| normalized.join(","))
}

fn valid_tracestate_key(key: &str) -> bool {
    let valid_rest = |value: &str| {
        value.bytes().all(|byte| {
            byte.is_ascii_lowercase()
                || byte.is_ascii_digit()
                || matches!(byte, b'_' | b'-' | b'*' | b'/')
        })
    };

    if let Some((tenant, system)) = key.split_once('@') {
        if system.contains('@')
            || tenant.is_empty()
            || tenant.len() > 241
            || system.is_empty()
            || system.len() > 14
        {
            return false;
        }
        let tenant_first = tenant.as_bytes()[0];
        let system_first = system.as_bytes()[0];
        (tenant_first.is_ascii_lowercase() || tenant_first.is_ascii_digit())
            && system_first.is_ascii_lowercase()
            && valid_rest(tenant)
            && valid_rest(system)
    } else {
        !key.is_empty()
            && key.len() <= 256
            && key.as_bytes()[0].is_ascii_lowercase()
            && valid_rest(key)
    }
}

fn valid_tracestate_value(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 256
        && value.as_bytes().last() != Some(&b' ')
        && value
            .bytes()
            .all(|byte| (b' '..=b'~').contains(&byte) && !matches!(byte, b',' | b'='))
}

fn new_trace_id() -> String {
    uuid::Uuid::new_v4().simple().to_string()
}

fn new_span_id() -> String {
    let uuid = uuid::Uuid::new_v4().simple().to_string();
    // UUID v4's lower 64 bits are random and avoid the fixed version/variant bits.
    uuid[16..].to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;
    use http::Request as HttpRequest;
    use std::convert::Infallible;
    use tower::{Layer, ServiceExt};

    const VALID_TRACEPARENT: &str = "00-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-01";

    #[test]
    fn parses_valid_trace_context_and_creates_a_distinct_server_span() {
        let mut headers = HeaderMap::new();
        headers.insert(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(VALID_TRACEPARENT),
        );
        headers.insert(TRACESTATE_HEADER, HeaderValue::from_static("vendor=opaque"));

        let context = TraceContext::from_headers(&headers);

        assert_eq!(context.trace_id(), "4bf92f3577b34da6a3ce929d0e0e4736");
        assert_eq!(context.parent_span_id(), Some("00f067aa0ba902b7"));
        assert_eq!(context.tracestate(), Some("vendor=opaque"));
        assert!(context.sampled());
        assert_ne!(context.span_id(), context.parent_span_id().unwrap());
        assert_eq!(context.traceparent().len(), 55);
    }

    #[test]
    fn persisted_traceparent_creates_a_fresh_async_child_without_vendor_state() {
        let context = TraceContext::child_from_traceparent(VALID_TRACEPARENT)
            .expect("valid persisted parent");

        assert_eq!(context.trace_id(), "4bf92f3577b34da6a3ce929d0e0e4736");
        assert_eq!(context.parent_span_id(), Some("00f067aa0ba902b7"));
        assert!(context.sampled());
        assert!(context.tracestate().is_none());
        assert_ne!(context.span_id(), context.parent_span_id().unwrap());
        assert!(TraceContext::child_from_traceparent("invalid").is_none());
    }

    #[test]
    fn downgrades_a_future_version_and_masks_reserved_trace_flags() {
        let mut headers = HeaderMap::new();
        headers.insert(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(
                "01-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-09-extra",
            ),
        );

        let context = TraceContext::from_headers(&headers);

        assert_eq!(context.trace_id(), "4bf92f3577b34da6a3ce929d0e0e4736");
        assert!(context.sampled());
        assert!(context.traceparent().ends_with("-01"));
    }

    #[test]
    fn malformed_or_duplicate_traceparents_restart_and_drop_tracestate() {
        for invalid in [
            "00-00000000000000000000000000000000-00f067aa0ba902b7-01",
            "00-4BF92F3577B34DA6A3CE929D0E0E4736-00f067aa0ba902b7-01",
            "ff-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-01",
            "00-4bf92f3577b34da6a3ce929d0e0e4736-0000000000000000-01",
        ] {
            let mut headers = HeaderMap::new();
            headers.insert(TRACEPARENT_HEADER, HeaderValue::from_str(invalid).unwrap());
            headers.insert(TRACESTATE_HEADER, HeaderValue::from_static("vendor=opaque"));
            let context = TraceContext::from_headers(&headers);
            assert_eq!(context.parent_span_id(), None);
            assert_eq!(context.tracestate(), None);
            assert!(!context.trace_id().chars().all(|character| character == '0'));
        }

        let mut headers = HeaderMap::new();
        headers.append(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(VALID_TRACEPARENT),
        );
        headers.append(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(VALID_TRACEPARENT),
        );
        headers.insert(TRACESTATE_HEADER, HeaderValue::from_static("vendor=opaque"));
        let context = TraceContext::from_headers(&headers);
        assert_eq!(context.parent_span_id(), None);
        assert_eq!(context.tracestate(), None);
    }

    #[test]
    fn combines_and_validates_tracestate_without_poisoning_a_valid_parent() {
        let mut headers = HeaderMap::new();
        headers.insert(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(VALID_TRACEPARENT),
        );
        headers.append(
            TRACESTATE_HEADER,
            HeaderValue::from_static(" vendor=opaque "),
        );
        headers.append(TRACESTATE_HEADER, HeaderValue::from_static("other=value"));

        let context = TraceContext::from_headers(&headers);
        assert_eq!(context.tracestate(), Some("vendor=opaque,other=value"));

        headers.insert(
            TRACESTATE_HEADER,
            HeaderValue::from_static("vendor=one,vendor=two"),
        );
        let context = TraceContext::from_headers(&headers);
        assert_eq!(context.parent_span_id(), Some("00f067aa0ba902b7"));
        assert_eq!(context.tracestate(), None);

        headers.remove(TRACEPARENT_HEADER);
        headers.insert(TRACESTATE_HEADER, HeaderValue::from_static("vendor=one"));
        let context = TraceContext::from_headers(&headers);
        assert_eq!(context.tracestate(), None);
    }

    #[tokio::test]
    async fn grpc_metadata_uses_the_current_server_span_as_parent() {
        let mut headers = HeaderMap::new();
        headers.insert(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(VALID_TRACEPARENT),
        );
        headers.insert(TRACESTATE_HEADER, HeaderValue::from_static("vendor=opaque"));
        let context = TraceContext::from_headers(&headers);
        let expected_trace_id = context.trace_id().to_owned();
        let expected_span_id = context.span_id().to_owned();

        CURRENT
            .scope(context, async {
                let mut request = Request::new(());
                attach(&mut request).expect("attach trace context");
                let traceparent = request.metadata().get(TRACEPARENT_HEADER).unwrap();
                let parsed =
                    parse_traceparent(traceparent.as_bytes()).expect("valid child context");
                assert_eq!(parsed.trace_id, expected_trace_id);
                assert_eq!(parsed.span_id, expected_span_id);
                assert_eq!(parsed.trace_flags, SAMPLED_FLAG);
                assert_eq!(
                    request.metadata().get(TRACESTATE_HEADER).unwrap(),
                    "vendor=opaque"
                );
            })
            .await;

        let mut outside_scope = Request::new(());
        outside_scope
            .metadata_mut()
            .insert(TRACEPARENT_HEADER, VALID_TRACEPARENT.parse().unwrap());
        attach(&mut outside_scope).expect("clear caller-supplied context");
        assert!(outside_scope.metadata().get(TRACEPARENT_HEADER).is_none());
    }

    #[tokio::test]
    async fn tower_layer_scopes_and_instruments_inbound_http_requests() {
        let service =
            TraceContextLayer.layer(tower::service_fn(|request: HttpRequest<()>| async move {
                let context = current();
                let method = request.method().clone();
                Ok::<_, Infallible>((context, method))
            }));
        let request = HttpRequest::builder()
            .method("GET")
            .header(TRACEPARENT_HEADER, VALID_TRACEPARENT)
            .body(())
            .unwrap();

        let (context, method) = service.oneshot(request).await.unwrap();

        let context = context.expect("server trace scope");
        assert_eq!(method, http::Method::GET);
        assert_eq!(context.parent_span_id(), Some("00f067aa0ba902b7"));
    }

    #[tokio::test]
    async fn local_child_span_keeps_the_validated_parent_and_does_not_replace_it() {
        let mut headers = HeaderMap::new();
        headers.insert(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(VALID_TRACEPARENT),
        );
        let parent = TraceContext::from_headers(&headers);
        let parent_span_id = parent.span_id().to_owned();
        let trace_id = parent.trace_id().to_owned();

        CURRENT
            .scope(parent, async {
                let span = tracing::info_span!(
                    "db_test",
                    trace_id = field::Empty,
                    span_id = field::Empty,
                    parent_span_id = field::Empty,
                    sampled = field::Empty,
                );
                let child = bind_current_child_to_span(&span).expect("current trace context");

                assert_eq!(child.trace_id(), trace_id);
                assert_eq!(child.parent_span_id(), Some(parent_span_id.as_str()));
                assert_ne!(child.span_id(), parent_span_id);
                assert_eq!(
                    current().expect("parent remains in scope").span_id(),
                    parent_span_id
                );
            })
            .await;
    }

    #[test]
    fn debug_output_never_includes_opaque_tracestate_values() {
        let mut headers = HeaderMap::new();
        headers.insert(
            TRACEPARENT_HEADER,
            HeaderValue::from_static(VALID_TRACEPARENT),
        );
        headers.insert(
            TRACESTATE_HEADER,
            HeaderValue::from_static("vendor=private-state-marker"),
        );
        let rendered = format!("{:?}", TraceContext::from_headers(&headers));
        assert!(rendered.contains("tracestate_present: true"));
        assert!(!rendered.contains("private-state-marker"));
    }
}
