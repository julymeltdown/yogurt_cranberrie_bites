#!/usr/bin/env python3
"""Read-only source geometry/pixel/resource verification; never edits images."""
from pathlib import Path
import json, hashlib, subprocess, sys, platform
from PIL import Image, __version__ as pillow_version
ROOT=Path(__file__).resolve().parents[5]
OUT=ROOT/'frontend/public/world/illustrated'
HERE=Path(__file__).resolve().parent
BASE='a5ff446b6fe9eedb825f16710216a1eeb8c00d5e'
def sha(b):return 'sha256:'+hashlib.sha256(b).hexdigest()
def canonical(o):return json.dumps(o,sort_keys=True,separators=(',',':'),ensure_ascii=True).encode('ascii')
def main():
 b=json.loads((OUT/'binding-proposal.json').read_text());g=json.loads((ROOT/'frontend/public/world/maps/geometry.json').read_text())
 assert (g['width_cells'],g['height_cells'],g['tile_width_px'],g['tile_height_px'])==(36,28,32,32)
 assert sha(canonical(g))==b['geometry_hash']
 assert b['spawns']==g['spawns'] and b['interactions']==g['interactions']
 immutable=[]
 for source in b['sources']:
  data=(ROOT/source['path']).read_bytes();expected=subprocess.check_output(['git','show',BASE+':'+source['path']],cwd=ROOT)
  assert data==expected and sha(data)==source['sha256']
  immutable.append(source)
 for o in b['placements']:
  x,y,w,h=o['footprint'];assert all(g['collision_grid'][yy][xx]==1 for yy in range(y,y+h)for xx in range(x,x+w)),o['id']
  sx,sy,sw,sh=o['atlas_frame'];assert 0<=sx<sx+sw<=768 and 0<=sy<sy+sh<=512
  assert o['depth_y']==o['y']+o['height']
 # Isolated atlas frames do not overlap except explicit reusable canopy aliases.
 frames=set(tuple(o['atlas_frame'])for o in b['placements'])
 for a in frames:
  for c in frames:
   if a==c:continue
   assert not(a[0]<c[0]+c[2] and c[0]<a[0]+a[2] and a[1]<c[1]+c[3] and c[1]<a[1]+a[3])
 receipt=json.loads((OUT/'exported-resources.json').read_text());resources=[]
 for r in receipt['resources']:
  p=ROOT/'frontend/public'/r['path'];data=p.read_bytes();im=Image.open(p);im.load()
  assert im.format=='PNG' and im.mode in ('RGB','RGBA') and im.size==(r['width_px'],r['height_px'])
  assert sha(data)==r['sha256'] and len(data)==r['bytes'] and len(data)<1048576
  assert max(im.size)<=2048
  if r['path'].endswith('-ground.png'):assert im.convert('RGBA').getchannel('A').getextrema()==(255,255)
  if r['path'].endswith('-terrain-tiles.png'):assert im.crop((0,32,256,128)).getbbox() is None
  resources.append(dict(path=r['path'],sha256=r['sha256'],bytes=len(data),dimensions=list(im.size)))
 assert len(resources)==15
 clear_targets=[];masks=[]
 for era in ['revenge','parade','danger']:
  fg=Image.open(OUT/f'{era}-landmarks.png');masks.append(fg.getchannel('A').tobytes())
  for interaction in g['interactions']:
   x,y=(interaction['cell_x']*32+16,interaction['cell_y']*32+16)
   assert g['collision_grid'][interaction['cell_y']][interaction['cell_x']]==0
   # A 28px clear disk contains no foreground scenery pixel at the target.
   samples=[fg.getpixel((x+dx,y+dy))[3]for dx in range(-14,15)for dy in range(-14,15)if dx*dx+dy*dy<=196]
   assert max(samples)==0,(era,interaction['interaction_id'],'foreground obscures target')
   clear_targets.append(dict(era=era,interaction=interaction['interaction_id'],radius_px=14,max_foreground_alpha=max(samples)))
 assert masks[0]==masks[1]==masks[2], 'theme-dependent alpha/footprint'
 originals=[]
 for p in sorted(OUT.glob('*-original.png')):
  im=Image.open(p);assert im.mode=='RGBA' and im.getchannel('A').getextrema()==(0,255)
  originals.append(dict(path=str(p.relative_to(ROOT)),sha256=sha(p.read_bytes()),dimensions=list(im.size),bytes=p.stat().st_size,source_state='Original generated bytes preserved'))
 assert len(originals)==5
 changed=subprocess.check_output(['git','diff',BASE,'--name-only'],cwd=ROOT,text=True).splitlines()
 others=subprocess.check_output(['git','ls-files','--others','--exclude-standard'],cwd=ROOT,text=True).splitlines()
 allowed=lambda p:p.startswith('frontend/public/world/illustrated/')or p.startswith('docs/mcr/art/evidence/illustrated-world/')or p=='docs/mcr/art/illustrated-world.md'
 assert all(allowed(p)for p in changed+others)
 report=dict(result='PASS',scope='Original illustrated source resources, immutable AR02 geometry and interaction visibility; not product acceptance',base=BASE,python=platform.python_version(),pillow=pillow_version,geometry_hash=b['geometry_hash'],immutable_sources=immutable,
  checks=['All source AR02 bytes identical to assigned base','Exact36x28,3spawns,5interactions and collision identity unchanged','All landmark roots assigned to existing blocked cells','Atlas frames bounded/nonoverlapping with explicit canopy aliases','All15 exports decoded, dimension/hash/byte-budget verified','Ground opaque; terrain-only unused rows transparent','All15 era×interaction target disks clear of foreground alpha','All three full-scene alpha footprints identical','Exactly five transparent original source images preserved','Only assigned new paths changed'],originals=originals,resources=resources,clear_targets=clear_targets,
  limitations=['No character compatibility or fallback','No real devices, live backend or actual application integration','Binding is proposal only; no C06 registry/manifests changed','Generated mural is decorative scenery, not live wall state'])
 (HERE/'resource-validation.json').write_text(json.dumps(report,indent=2)+'\n');print('PASS: immutable geometry,17 root placements,15 exports,15 clear interaction disks and source-only scope')
if __name__=='__main__':main()
